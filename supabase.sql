-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.allies (
  id bigint generated by default as identity primary key,
  username text not null,
  created_at timestamptz not null default now(),
  constraint allies_username_format check (username ~ '^[A-Za-z0-9_]{3,20}$')
);

create unique index if not exists allies_username_lower_unique
on public.allies (lower(username));

alter table public.allies enable row level security;

-- Public community list: visitors can view, add, and remove entries.
-- WARNING: without authentication, anyone can delete entries. This is intentionally
-- simple for a public prototype; use sign-in/admin moderation for a serious launch.
drop policy if exists "Public can view allies" on public.allies;
create policy "Public can view allies"
on public.allies for select
to anon, authenticated
using (true);

drop policy if exists "Public can add allies" on public.allies;
create policy "Public can add allies"
on public.allies for insert
to anon, authenticated
with check (username ~ '^[A-Za-z0-9_]{3,20}$');

drop policy if exists "Public can delete allies" on public.allies;
create policy "Public can delete allies"
on public.allies for delete
to anon, authenticated
using (true);

grant select, insert, delete on public.allies to anon, authenticated;
grant usage, select on sequence public.allies_id_seq to anon, authenticated;

